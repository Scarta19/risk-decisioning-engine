"""Render the evaluation report (Markdown + PNG figures) from pipeline outputs."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

SURFACE, INK, MUTED, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
BLUE, ORANGE = "#2a78d6", "#eb6834"

POLICY_LABELS = {
    "approve_all": "Approve everything",
    "single_threshold": "Single score threshold",
    "cost_policy_no_review": "Cost policy, no review lane",
    "cost_policy": "Cost policy with review lane",
}


def _style(ax, title: str) -> None:
    ax.set_facecolor(SURFACE)
    ax.set_title(title, loc="left", color=INK, fontsize=12, pad=12)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=MUTED, labelsize=9)
    ax.grid(color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def render_figures(metrics: dict, test_frame: pd.DataFrame, out_dir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from sklearn.metrics import precision_recall_curve

    out_dir.mkdir(parents=True, exist_ok=True)
    y = test_frame["is_fraud"].to_numpy()
    paths = []

    # 1. Reliability diagram (log-log: fraud is rare, the interesting range is small p).
    fig, ax = plt.subplots(figsize=(6, 4.6), facecolor=SURFACE)
    _style(ax, "Calibration on the test window (bins with at least 50 events)")
    edges = np.logspace(-4, 0, 13)  # log-spaced bins: most events have tiny scores
    for col, color, label in (("raw_score", ORANGE, "Raw LightGBM"), ("p", BLUE, "Calibrated")):
        score = test_frame[col].to_numpy()
        b = pd.Series(np.digitize(score, edges))
        t = (
            pd.DataFrame({"p": score, "y": y})
            .groupby(b.to_numpy())
            .agg(predicted=("p", "mean"), observed=("y", "mean"), n=("y", "size"))
        )
        t = t[(t["n"] >= 50) & (t["observed"] > 0)]
        ax.plot(
            t["predicted"],
            t["observed"],
            "-o",
            color=color,
            lw=2,
            ms=6,
            label=label,
            markeredgecolor=SURFACE,
            markeredgewidth=2,
        )
    lims = [1e-4, 1]
    ax.plot(lims, lims, ls="--", color=MUTED, lw=1, label="Perfect calibration")
    ax.set(xscale="log", yscale="log", xlim=lims, ylim=lims)
    ax.set_xlabel("Mean predicted fraud probability", color=MUTED)
    ax.set_ylabel("Observed fraud rate", color=MUTED)
    ax.legend(frameon=False, fontsize=9, labelcolor=INK)
    fig.tight_layout()
    paths.append(out_dir / "calibration.png")
    fig.savefig(paths[-1], dpi=160)
    plt.close(fig)

    # 2. Precision-recall curve.
    prec, rec, _ = precision_recall_curve(y, test_frame["p"].to_numpy())
    fig, ax = plt.subplots(figsize=(6, 4.6), facecolor=SURFACE)
    _style(ax, "Precision-recall on the test window")
    ax.plot(rec, prec, color=BLUE, lw=2)
    ap = metrics["ranking_test"]["average_precision"]
    ax.text(0.03, 0.06, f"Average precision {ap:.3f}", transform=ax.transAxes, color=INK)
    ax.set(xlim=(0, 1), ylim=(0, 1.02))
    ax.set_xlabel("Recall", color=MUTED)
    ax.set_ylabel("Precision", color=MUTED)
    fig.tight_layout()
    paths.append(out_dir / "precision_recall.png")
    fig.savefig(paths[-1], dpi=160)
    plt.close(fig)

    # 3. Business cost by policy.
    table = pd.DataFrame(metrics["policies_test"])
    labels = [POLICY_LABELS.get(p, p) for p in table["policy"]]
    fig, ax = plt.subplots(figsize=(7, 3.4), facecolor=SURFACE)
    _style(ax, "Business cost per 1,000 events (test window, illustrative costs)")
    ax.grid(axis="y", visible=False)
    bars = ax.barh(labels[::-1], table["cost_per_1k_events"][::-1], color=BLUE, height=0.55)
    for bar in bars:
        ax.text(
            bar.get_width(),
            bar.get_y() + bar.get_height() / 2,
            f"  ${bar.get_width():,.0f}",
            va="center",
            color=INK,
            fontsize=9,
        )
    ax.set_xlim(0, table["cost_per_1k_events"].max() * 1.18)
    ax.tick_params(axis="y", colors=INK)
    fig.tight_layout()
    paths.append(out_dir / "policy_cost.png")
    fig.savefig(paths[-1], dpi=160)
    plt.close(fig)
    return paths


def _pct(x: float) -> str:
    return "n/a" if x != x else f"{100 * x:.2f}%"


def render_markdown(metrics: dict, figures_rel: str = "figures") -> str:
    md, d = metrics["metadata"], metrics["data"]
    r, c = metrics["ranking_test"], metrics["calibration_test"]
    lines = [
        "# Evaluation report",
        "",
        "> Generated by `rde run`. All numbers come from **synthetic data** produced by this",
        "> repository's simulator and **illustrative cost assumptions** in the config. They",
        "> demonstrate the method; they are not estimates of real-world fraud performance.",
        "",
        f"Model version `{md['model_version']}` · best iteration {md['best_iteration']} · "
        f"calibration `{md['calibration_method']}`",
        "",
        "## Data and out-of-time split",
        "",
        "| Window | Dates | Events | Fraud rate |",
        "|---|---|---:|---:|",
    ]
    for k, v in d["by_split"].items():
        lines.append(f"| {k} | {md['trained_on'][k]} | {v['events']:,} | {_pct(v['fraud_rate'])} |")
    lines += [
        "",
        "Train fits the model, valid drives early stopping, calib fits the calibrator, the",
        "review shadow price and the baseline threshold, and test is touched only once.",
        "",
        "## Ranking (test window)",
        "",
        "| ROC AUC | Average precision | Base rate |",
        "|---:|---:|---:|",
        f"| {r['roc_auc']:.3f} | {r['average_precision']:.3f} | {_pct(r['base_rate'])} |",
        "",
        f"![Precision-recall]({figures_rel}/precision_recall.png)",
        "",
        "## Calibration (test window)",
        "",
        "| Scores | Brier | Log loss | ECE |",
        "|---|---:|---:|---:|",
    ]
    for k in ("raw", "calibrated"):
        v = c[k]
        lines.append(f"| {k} | {v['brier']:.5f} | {v['log_loss']:.5f} | {v['ece']:.5f} |")
    sel = metrics["calibration_selection_logloss"]
    lines += [
        "",
        "Calibrator selection (log loss on the most recent third of the calib window): "
        + ", ".join(f"{k} {v:.5f}" for k, v in sel.items())
        + ".",
        "",
        f"![Calibration]({figures_rel}/calibration.png)",
        "",
        "## Decisions and business cost (test window)",
        "",
        "| Policy | Cost / 1k events | Approve | Review | Decline | Fraud intercepted "
        "| Fraud $ intercepted | Legit declined | Review precision |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for p in metrics["policies_test"]:
        lines.append(
            f"| {POLICY_LABELS.get(p['policy'], p['policy'])} | ${p['cost_per_1k_events']:,.0f} "
            f"| {_pct(p['approve_rate'])} | {_pct(p['review_rate'])} | {_pct(p['decline_rate'])} "
            f"| {_pct(p['fraud_intercepted_rate'])} | {_pct(p['fraud_amount_intercepted_rate'])} "
            f"| {_pct(p['legit_declined_rate'])} | {_pct(p['review_precision'])} |"
        )
    lines += [
        "",
        f"Review shadow price fitted on the calib window: ${md['review_price']:.2f} "
        "(0 means the capacity limit was not binding). Single-threshold baseline cut-off: "
        f"{md['single_threshold']:.4f}.",
        "",
        f"![Policy cost]({figures_rel}/policy_cost.png)",
        "",
        "## Interception by fraud pattern (cost policy, test window)",
        "",
        "| Pattern | Fraud events | Reviewed or declined |",
        "|---|---:|---:|",
    ]
    for p in metrics["pattern_recall_test"]:
        lines.append(f"| {p['fraud_pattern']} | {p['events']} | {_pct(p['intercepted_rate'])} |")
    psi = sorted(metrics["psi_train_vs_test"].items(), key=lambda kv: -kv[1])[:6]
    imp = sorted(metrics["feature_importance_gain"].items(), key=lambda kv: -kv[1])[:8]
    total = sum(metrics["feature_importance_gain"].values()) or 1.0
    lines += [
        "",
        "## Feature drift, train vs test (PSI, top 6)",
        "",
        "| Feature | PSI |",
        "|---|---:|",
        *[f"| `{k}` | {v:.3f} |" for k, v in psi],
        "",
        "Rule of thumb: below 0.1 stable, 0.1 to 0.25 watch, above 0.25 investigate.",
        "",
        "## Feature importance (gain share, top 8)",
        "",
        "| Feature | Share |",
        "|---|---:|",
        *[f"| `{k}` | {100 * v / total:.1f}% |" for k, v in imp],
        "",
    ]
    return "\n".join(lines)


def write_report(metrics: dict, test_frame: pd.DataFrame, reports_dir: Path) -> Path:
    reports_dir.mkdir(parents=True, exist_ok=True)
    render_figures(metrics, test_frame, reports_dir / "figures")
    path = reports_dir / "evaluation.md"
    path.write_text(render_markdown(metrics))
    return path
